(() => {
  let language = 'en';
  try { language = localStorage.getItem('gamePou-language') === 'zh-Hant' ? 'zh-Hant' : 'en'; } catch {}
  const textSources = new Map();
  const attributeSources = [];
  function translate(text) {
    if (language === 'en') return text;
    if (translations[text]) return translations[text];
    const counting = text.match(/^Correct! Answer: (\d+) underscores\. Guesses: (\d+)\.$/);
    if (counting) return `啱喇！答案係 ${counting[1]} 條底線。你估咗 ${counting[2]} 次。`;
    const pieces = text.match(/^Pieces: (\d+) · Friends you can share with: (\d+)$/);
    if (pieces) return `紙巾：${pieces[1]} 塊 · 可以分俾 ${pieces[2]} 個朋友`;
    const over = text.match(/^Empty space! Run over\. You made (\d+) pieces to share with (\d+) friends\. Start a fresh tissue to try again\.$/);
    if (over) return `搣咗落空隙，玩完喇！你分咗 ${over[1]} 塊紙巾，可以分俾 ${over[2]} 個朋友。換張紙巾再嚟過啦。`;
    const correct = text.match(/^Correct! There are (\d+) underscores\. Ready for another round\?$/);
    if (correct) return `啱喇！有 ${correct[1]} 條底線。再玩鋪？`;
    const result = text.match(/^Score: ([\d.]+)\/100 \(higher is better\)\. Your pieces are ([\d.]+)% and ([\d.]+)% of the tissue\. Straightness: ([\d.]+)%\. Verticality: ([\d.]+)%\. (.*)$/);
    if (result) return `分數：${result[1]}/100（越高越好）。兩邊分別佔 ${result[2]}% 同 ${result[3]}%。直唔直：${result[4]}%。有幾垂直：${result[5]}%。${result[6].startsWith('Beautifully') ? '搣得夠均勻，條線又夠直，靚！' : '換張紙巾，再試吓攞高啲分啦。'}`;
    return text;
  }
  const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest('script, style, #language-switch')) continue;
    if (node.textContent.trim()) textSources.set(node, node.textContent);
  }
  document.querySelectorAll('[aria-label], meta[name="description"]').forEach(element => {
    for (const name of ['aria-label', 'content']) {
      if (element.hasAttribute(name)) attributeSources.push([element, name, element.getAttribute(name)]);
    }
  });
  const dynamic = new Map();
  function apply() {
    document.documentElement.lang = language;
    textSources.forEach((source, node) => {
      if (node.isConnected && !dynamic.has(node.parentElement)) {
        node.textContent = source.replace(/\S[\s\S]*\S|\S/, text => translate(text));
      }
    });
    attributeSources.forEach(([element, name, source]) => element.setAttribute(name, translate(source)));
    dynamic.forEach((source, element) => { element.textContent = translate(source); });
    const button = document.getElementById('language-switch');
    button.textContent = language === 'en' ? '繁體中文' : 'English';
    button.setAttribute('aria-label', language === 'en' ? '切換至繁體中文' : 'Switch to English');
  }
  window.i18n = {
    set(element, english) {
      dynamic.set(element, english);
      element.textContent = translate(english);
    }
  };
  document.getElementById('language-switch').addEventListener('click', () => {
    language = language === 'en' ? 'zh-Hant' : 'en';
    try { localStorage.setItem('gamePou-language', language); } catch {}
    apply();
  });
  apply();
})();
